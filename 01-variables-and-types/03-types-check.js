const a = "42";
console.log(a);
console.log(typeof a); // string

const b = 42;
console.log(b);
console.log(typeof b); // number

const c = false;
console.log(c);
console.log(typeof c); // boolean

const d = null;
console.log(d);
console.log(typeof d); // object

const e = undefined;
console.log(e);
console.log(typeof e); // undefined

const f = NaN;
console.log(f);
console.log(typeof f); // number
